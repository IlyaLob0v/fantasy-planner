/** Сколько глав заслужено к этому числу дней в походе. */
export function sagaEarned(journeyDays: number, everyDays: number): number {
  if (everyDays <= 0) return 0;
  return Math.min(SAGA.length, Math.floor(journeyDays / everyDays));
}

/** Заслуженные, но ещё не записанные главы, по порядку. Глава не отбирается. */
export function newSagaChapters(journeyDays: number, everyDays: number, unlocked: readonly string[]): SagaChapter[] {
  const opened = new Set(unlocked);
  return SAGA.slice(0, sagaEarned(journeyDays, everyDays)).filter((ch) => !opened.has(ch.key));
}

/** Через сколько дней в походе откроется следующая глава; null, когда сказ прочитан до конца. */
export function nextChapterIn(journeyDays: number, everyDays: number): number | null {
  const earned = sagaEarned(journeyDays, everyDays);
  if (earned >= SAGA.length || everyDays <= 0) return null;
  return (earned + 1) * everyDays - journeyDays;
}

export function sagaChapter(key: string): SagaChapter | undefined {
  return SAGA.find((ch) => ch.key === key);
}
