import { favoriteAttribute } from "./journey";
import type { Attribute, Character } from "./types";

/**
 * Сказ о герое: главы открываются по дням в походе, не подряд. Тексты живут здесь по стабильным ключам,
 * в базе только факт «открыта» и «прочитана». Герой говорится на «ты» и в настоящем времени:
 * так текст не угадывает род.
 */
export interface SagaContext {
  name: string;
  /** Чем силён герой: по самому развитому атрибуту. */
  gift: string;
  /** Где сейчас штаб, в именительном падеже: в тексте стоит только подлежащим. */
  home: string;
  /** Последний побеждённый босс, если был. */
  boss: string | null;
}

export interface SagaChapter {
  key: string;
  title: string;
  text: (c: SagaContext) => string[];
}

const GIFT: Record<Attribute, string> = {
  strength: "крепкие руки",
  intellect: "ясный ум",
  agility: "быстрые пальцы",
};

export function sagaContext(character: Character, home: string, boss: string | null): SagaContext {
  const favorite = favoriteAttribute(character);
  return { name: character.name, gift: favorite ? GIFT[favorite] : "упрямое сердце", home, boss };
}

function chapter(n: number, title: string, text: (c: SagaContext) => string[]): SagaChapter {
  return { key: `saga_${String(n).padStart(2, "0")}`, title, text };
}

